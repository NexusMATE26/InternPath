"""Deterministic factual grounding and validation layer for InternPath Agentic AI (R2.3).

Verifies that model decisions, recommendations, and staged proposals are grounded
in authoritative tool executions, C++ planner outputs, and database facts.

Architectural Principles:
- THE AI PROPOSES. THE ALGORITHMS VALIDATE. THE STUDENT DECIDES.
- Never allow hallucinated simulation IDs, fabricated weekly study hours, or invented feasibility.
- Unverified third-party claims or mock role fixtures must never be presented as verified employer vacancies.
- Mandatory competencies and completed student milestones must be strictly preserved.
"""
import re
import logging
from typing import Any, Optional
from pydantic import BaseModel, Field

from app.schemas import AgentDecisionResult, ValidityStatus

logger = logging.getLogger("internpath.agent.grounding")


class GroundingViolation(BaseModel):
    """Specific factual grounding discrepancy detected in model output."""
    category: str = Field(description="Violation category (e.g. fake_simulation_id, hallucinated_hours, feasibility_inversion)")
    message: str = Field(description="Detailed explanation of the factual violation")
    severity: str = Field(default="error", description="Severity level: 'error' or 'warning'")


class GroundingValidationResult(BaseModel):
    """Result of factual grounding validation for an agent decision."""
    is_grounded: bool = Field(description="True if all assertions are backed by deterministic tool output")
    status: str = Field(description="'grounded', 'flagged_with_warnings', or 'rejected_unsupported'")
    violations: list[GroundingViolation] = Field(default_factory=list)
    validated_decision: AgentDecisionResult = Field(description="Original or safely adjusted decision")
    grounding_metadata: dict[str, Any] = Field(default_factory=dict)


class GroundingValidator:
    """Deterministic validator verifying agent claims against authoritative tool executions."""

    SIMULATION_ID_PATTERN = re.compile(r"\b(sim_[a-zA-Z0-9_\-]+)\b")
    HOURS_PATTERN = re.compile(r"\b(\d{1,2})\s*(?:hrs?/week|hours/week|h/wk|hours\s+per\s+week)\b", re.IGNORECASE)

    @classmethod
    def validate_decision(
        cls,
        decision: AgentDecisionResult,
        tools_invoked: list[str],
        tool_io_log: list[dict[str, Any]],
        simulation_cache: dict[str, dict[str, Any]],
        active_mission: Optional[Any] = None,
        event_context: Optional[dict[str, Any]] = None,
    ) -> GroundingValidationResult:
        """Perform comprehensive deterministic factual validation on final agent decision."""
        violations: list[GroundingViolation] = []
        grounding_meta: dict[str, Any] = {
            "simulations_executed_count": len(simulation_cache),
            "simulations_referenced": [],
            "hours_checked": [],
            "feasibility_checked": True,
        }

        full_text = f"{decision.explanation} {decision.recommended_action} {' '.join(decision.tradeoffs)} {decision.suggested_proposal_title or ''} {decision.suggested_proposal_rationale or ''}"

        # -------------------------------------------------------------
        # 1. Simulation Provenance & Existence
        # -------------------------------------------------------------
        referenced_sim_ids = set(cls.SIMULATION_ID_PATTERN.findall(full_text))
        grounding_meta["simulations_referenced"] = list(referenced_sim_ids)

        for sim_id in referenced_sim_ids:
            if sim_id not in simulation_cache:
                violations.append(
                    GroundingViolation(
                        category="fake_simulation_id",
                        message=f"Referenced simulation ID '{sim_id}' was never generated by simulate_plan_variant in this execution.",
                        severity="error",
                    )
                )
            else:
                sim_data = simulation_cache[sim_id]
                # Check mission identity and base version
                if active_mission:
                    if sim_data.get("mission_id") != active_mission.id:
                        violations.append(
                            GroundingViolation(
                                category="cross_mission_simulation",
                                message=f"Simulation '{sim_id}' belongs to mission {sim_data.get('mission_id')}, not active mission {active_mission.id}.",
                                severity="error",
                            )
                        )
                    active_ver = getattr(active_mission, "active_version", None)
                    if active_ver and sim_data.get("base_version_number") != active_ver.version_number:
                        violations.append(
                            GroundingViolation(
                                category="stale_simulation_version",
                                message=(
                                    f"Simulation '{sim_id}' was generated against version {sim_data.get('base_version_number')}, "
                                    f"which is stale against active version {active_ver.version_number}."
                                ),
                                severity="error",
                            )
                        )

        # -------------------------------------------------------------
        # 2. Feasibility Inversion Check
        # -------------------------------------------------------------
        # If any executed simulation was INVALID, the decision must not propose it as an adjustment
        if decision.decision_category == "proposed_mission_adjustment":
            if (
                not simulation_cache
                and "simulate_plan_variant" not in tools_invoked
                and "create_mission_change_proposal" not in tools_invoked
            ):
                # Proposing a plan adjustment without any simulation or proposal tool execution is ungrounded
                violations.append(
                    GroundingViolation(
                        category="unsimulated_proposal",
                        message="Agent proposed a mission adjustment without executing plan simulation or staging a proposal via authorized tools.",
                        severity="error",
                    )
                )
            else:
                for s_id, s_data in simulation_cache.items():
                    v_status = s_data.get("validity_status")
                    if v_status == ValidityStatus.INVALID.value:
                        # If model recommends an invalid plan
                        if s_id in referenced_sim_ids or len(simulation_cache) == 1:
                            violations.append(
                                GroundingViolation(
                                    category="invalid_plan_recommended",
                                    message=f"Simulation '{s_id}' was marked INVALID by C++ engine, but agent recommended a plan adjustment.",
                                    severity="error",
                                )
                            )
                    elif v_status == ValidityStatus.VALID_BUT_INFEASIBLE.value:
                        # Model can recommend it ONLY IF it explicitly acknowledges infeasibility/overload
                        # Strip simulation IDs to avoid accidental substring matches
                        text_without_sim_ids = cls.SIMULATION_ID_PATTERN.sub("", full_text).lower()
                        disclosure_keywords = ["infeasible", "exceeds", "tradeoff", "trade-off", "overload", "burnout", "capacity limit", "too demanding"]
                        if not any(k in text_without_sim_ids for k in disclosure_keywords):
                            violations.append(
                                GroundingViolation(
                                    category="unacknowledged_infeasibility",
                                    message=f"Simulation '{s_id}' exceeds undergraduate pacing thresholds, but explanation did not disclose capacity limitations.",
                                    severity="warning",
                                )
                            )

        # -------------------------------------------------------------
        # 3. Numeric Claim Grounding (Weekly Hours)
        # -------------------------------------------------------------
        stated_hours = [int(h) for h in cls.HOURS_PATTERN.findall(full_text)]
        grounding_meta["hours_checked"] = stated_hours

        if stated_hours and simulation_cache:
            authorized_hours = set()
            for s in simulation_cache.values():
                if "permitted_weekly_hours" in s:
                    authorized_hours.add(s["permitted_weekly_hours"])
            if active_mission and getattr(active_mission, "weekly_hours", None):
                authorized_hours.add(active_mission.weekly_hours)

            for h in stated_hours:
                # If stated hours are completely fabricated and don't match any simulated hours or active mission
                if h not in authorized_hours:
                    violations.append(
                        GroundingViolation(
                            category="hallucinated_hours",
                            message=f"Stated weekly commitment ({h} hrs/week) does not match any simulated variant or student baseline {authorized_hours}.",
                            severity="error",
                        )
                    )

        # -------------------------------------------------------------
        # 4. Mandatory Competencies & Completed Tasks Preservation
        # -------------------------------------------------------------
        for s in simulation_cache.values():
            if s.get("completed_work_preserved") is False:
                violations.append(
                    GroundingViolation(
                        category="work_preservation_violation",
                        message="Plan simulation violated completed task preservation invariant.",
                        severity="error",
                    )
                )
            if s.get("mandatory_requirements_preserved") is False:
                violations.append(
                    GroundingViolation(
                        category="mandatory_skills_violation",
                        message="Plan simulation dropped mandatory core role competencies.",
                        severity="error",
                    )
                )

        # -------------------------------------------------------------
        # 5. External Source & Employer Claim Grounding
        # -------------------------------------------------------------
        if event_context:
            source_rel = event_context.get("source_reliability", "")
            # If source is unverified third-party or academic demo fixture
            if source_rel == "unverified_third_party":
                if "verified by employer" in full_text.lower() or "confirmed by company" in full_text.lower():
                    violations.append(
                        GroundingViolation(
                            category="false_employer_verification",
                            message="Event originates from unverified third-party, but agent claimed it was verified by employer.",
                            severity="error",
                        )
                    )

        # -------------------------------------------------------------
        # 6. Synthesize Grounding Verdict and Safe Adjustments
        # -------------------------------------------------------------
        has_errors = any(v.severity == "error" for v in violations)
        has_warnings = any(v.severity == "warning" for v in violations)

        validated_decision = decision.model_copy()

        if has_errors:
            # Safe Fallback: Elevate to human review if severe factual hallucinations occurred
            error_msgs = "; ".join(v.message for v in violations if v.severity == "error")
            logger.warning("Factual grounding rejection: %s", error_msgs)

            validated_decision.decision_category = "human_review_required"
            validated_decision.explanation = (
                f"[Factual Grounding Guard] Model decision required adjustment due to unverified claims: {error_msgs}. "
                f"Original reasoning: {decision.explanation}"
            )
            validated_decision.confidence_score = min(decision.confidence_score, 0.4)
            validated_decision.tradeoffs.append("Grounding validation intercepted unsupported factual claims.")

            return GroundingValidationResult(
                is_grounded=False,
                status="rejected_unsupported",
                violations=violations,
                validated_decision=validated_decision,
                grounding_metadata=grounding_meta,
            )

        elif has_warnings:
            # Informational warnings: preserve decision category but append advisory note
            warn_msgs = "; ".join(v.message for v in violations if v.severity == "warning")
            logger.info("Factual grounding warning: %s", warn_msgs)
            validated_decision.tradeoffs.append(f"Grounding advisory: {warn_msgs}")

            return GroundingValidationResult(
                is_grounded=True,
                status="flagged_with_warnings",
                violations=violations,
                validated_decision=validated_decision,
                grounding_metadata=grounding_meta,
            )

        return GroundingValidationResult(
            is_grounded=True,
            status="grounded",
            violations=[],
            validated_decision=validated_decision,
            grounding_metadata=grounding_meta,
        )
