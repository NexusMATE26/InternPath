"""Provider-neutral models and execution trace data structures for InternPath Agentic AI (R2.2).

Defines clean internal representations for:
- AgentMessage / MessageRole
- ToolCall / ToolResult
- ModelTurnResponse
- AgentTurnRecord
- AgentExecutionTrace
- AgentQueryRequest
"""
from typing import Any, Optional
from pydantic import BaseModel, Field

from app.schemas import AgentDecisionResult, ToolDefinition


class ToolCall(BaseModel):
    """Normalized tool invocation request initiated by the model."""
    id: str = Field(description="Unique tool call identifier (e.g. from provider or generated)")
    name: str = Field(description="Name of the target tool in AgentToolRegistry")
    arguments: dict[str, Any] = Field(default_factory=dict, description="Parsed JSON arguments supplied by model")


class ToolResult(BaseModel):
    """Normalized tool execution result returned back to the model conversation."""
    call_id: str = Field(description="Matching tool call identifier")
    tool_name: str = Field(description="Executed tool name")
    output: Any = Field(description="Sanitized structured result returned by the tool")
    is_error: bool = Field(default=False, description="True if execution failed or raised an exception")
    error_message: Optional[str] = Field(default=None, description="Error message if execution failed")


class AgentMessage(BaseModel):
    """Provider-agnostic conversational message exchanged between agent loop and LLM."""
    role: str = Field(
        pattern="^(system|user|assistant|tool)$",
        description="Role of message sender: system, user, assistant, or tool",
    )
    content: Optional[Any] = Field(default=None, description="Body of message (text, structured dict, or null)")
    tool_calls: Optional[list[ToolCall]] = Field(default=None, description="Tool calls initiated by assistant")
    tool_call_id: Optional[str] = Field(default=None, description="Matching call ID when role is 'tool'")
    name: Optional[str] = Field(default=None, description="Tool name when role is 'tool'")


class ModelTurnResponse(BaseModel):
    """Normalized response from an LLM provider for a single generation turn."""
    content: Optional[str] = Field(default=None, description="Text content generated by model, if any")
    tool_calls: list[ToolCall] = Field(default_factory=list, description="List of tool calls requested by model")
    usage: dict[str, int] = Field(default_factory=dict, description="Token usage metadata")
    raw_response: Optional[dict[str, Any]] = Field(default=None, description="Raw provider response payload")


class AgentTurnRecord(BaseModel):
    """Detailed audit record for a single round-trip turn in the bounded tool loop."""
    turn_index: int = Field(description="1-based turn number in the multi-turn interaction")
    model_tool_calls: list[dict[str, Any]] = Field(default_factory=list, description="Tool calls requested in this turn")
    tool_results: list[dict[str, Any]] = Field(default_factory=list, description="Results of tool executions")
    assistant_message: Optional[str] = Field(default=None, description="Assistant text response if produced")
    duration_ms: int = Field(default=0, description="Turn execution time in milliseconds")


class AgentExecutionTrace(BaseModel):
    """Complete, explainable audit trace of a bounded multi-turn agent decision run."""
    engine_used: str = Field(description="Truthful label of engine used (e.g. gemini:gemini-1.5-flash, mock_llm, deterministic_rules)")
    decision: AgentDecisionResult = Field(description="Structured final decision synthesis")
    turns: list[AgentTurnRecord] = Field(default_factory=list, description="Chronological record of loop turns")
    tools_invoked: list[str] = Field(default_factory=list, description="Sequence of tool names invoked")
    tool_io_log: list[dict[str, Any]] = Field(default_factory=list, description="Complete sanitized tool I/O records")
    total_tool_calls: int = Field(default=0, description="Total number of tool calls executed")
    proposal_id: Optional[int] = Field(default=None, description="ID of pending mission proposal staged, if any")
    total_tokens: int = Field(default=0, description="Total tokens consumed across all model turns")
    execution_time_ms: int = Field(default=0, description="Total elapsed time in milliseconds")
    fallback_used: bool = Field(default=False, description="True if fallback to deterministic rules occurred")
    fallback_reason: Optional[str] = Field(default=None, description="Explanation of why fallback was triggered")


class AgentQueryRequest(BaseModel):
    """Student query or scenario request for conversational agent guidance."""
    query: str = Field(
        min_length=3,
        max_length=1000,
        description="Student question, constraint change, or scenario description",
    )
    context_role_id: Optional[str] = Field(
        default=None,
        description="Optional explicit role ID context (defaults to student active mission target role)",
    )
    simulated: bool = Field(
        default=False,
        description="Whether this query is triggered in presentation / simulation mode",
    )
